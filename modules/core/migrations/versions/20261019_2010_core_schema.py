# NULLIF trata o parâmetro não definido como NULL, e a comparação com NULL não casa com
# nenhuma linha. O padrão passa a ser negar: esquecer de definir o tenant não vaza dados,
# apenas não retorna nada.
_PREDICATE = f"tenant_id = NULLIF(current_setting('{TENANT_GUC}', true), '')::uuid"


def _enable_row_level_security() -> None:
    for table in TENANT_SCOPED_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        # FORCE faz a política valer também para o dono da tabela. Sem isso, qualquer
        # conexão que use o papel dono enxerga todas as empresas.
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
        op.execute(
            f"""
            CREATE POLICY tenant_isolation ON {table}
            FOR ALL
            USING ({_PREDICATE})
            WITH CHECK ({_PREDICATE})
            """
        )

    # A trilha de auditoria só aceita inserção. Políticas RESTRICTIVE são combinadas com
    # E, então estas se somam ao isolamento acima em vez de abrir exceção a ele.
    op.execute(
        "CREATE POLICY audit_log_no_update ON audit_log AS RESTRICTIVE FOR UPDATE USING (false)"
    )
    op.execute(
        "CREATE POLICY audit_log_no_delete ON audit_log AS RESTRICTIVE FOR DELETE USING (false)"
    )


